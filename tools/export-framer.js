/*
 * Exports the site content (site/js/data.js) in formats Framer can take:
 *   framer/cms/categories.csv, industries.csv, projects.csv   -> CMS "Import from CSV"
 *   framer/components/ProjectsData.ts                          -> data file used by the ProjectsExplorer code component
 * Run: node export-framer.js
 */
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const ROOT = path.resolve(__dirname, '..');
const ctx = { window: {} };
vm.createContext(ctx);
vm.runInContext(fs.readFileSync(path.join(ROOT, 'site', 'js', 'data.js'), 'utf8'), ctx);
const S = ctx.window.SITE;

const outCms = path.join(ROOT, 'framer', 'cms');
const outCmp = path.join(ROOT, 'framer', 'components');
fs.mkdirSync(outCms, { recursive: true });
fs.mkdirSync(outCmp, { recursive: true });

const csvCell = (v) => '"' + String(v == null ? '' : v).replace(/"/g, '""') + '"';
const csv = (rows) => '﻿' + rows.map((r) => r.map(csvCell).join(',')).join('\r\n') + '\r\n';
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const catName = (id) => S.categories.find((c) => c.id === id).name;
const indName = (id) => S.industries.find((c) => c.id === id).name;

fs.writeFileSync(path.join(outCms, 'categories.csv'), csv([['Title', 'Slug', 'Order'], ...S.categories.map((c, i) => [c.name, c.id, i + 1])]));
fs.writeFileSync(path.join(outCms, 'industries.csv'), csv([['Title', 'Slug', 'Order'], ...S.industries.map((c, i) => [c.name, c.id, i + 1])]));

// Write-up as HTML for a Framer "Formatted text" field (headings + paragraphs + lists; images are placed in Framer).
function writeupHTML(p) {
  const out = [];
  p.blocks.forEach((b) => {
    if (b.type === 'section') {
      out.push('<h2>' + esc(b.title) + '</h2>');
      (b.paras || []).forEach((t) => out.push('<p>' + esc(t) + '</p>'));
      if (b.stats) out.push('<ul>' + b.stats.map((s) => '<li><strong>' + esc(s.n) + '</strong> ' + esc(s.l) + '</li>').join('') + '</ul>');
      else if (b.bullets) out.push('<ul>' + b.bullets.map((t) => '<li>' + esc(t) + '</li>').join('') + '</ul>');
    } else if (b.type === 'media' && b.heading) {
      out.push('<h2>' + esc(b.heading) + '</h2>');
      b.items.forEach((m) => { if (m.t === 'vimeo') out.push('<p><a href="https://vimeo.com/' + m.id + '">' + esc(m.title || 'Watch on Vimeo') + '</a></p>'); });
    }
  });
  return out.join('\n');
}
function imageList(p) {
  const files = [];
  const add = (m) => { if (m && m.src && (m.t === 'img' || m.t === 'scroll')) files.push('site/assets/img/' + m.src); };
  add(p.lead);
  p.blocks.forEach((b) => { (b.media || []).forEach(add); (b.items || []).forEach(add); });
  return files.join('; ');
}
// One compact line of the published results, shown at the top of each project page (same figures as the Outcome section; none invented)
function keyResults(p) {
  const b = p.blocks.filter((x) => x.stats)[0];
  if (!b) return '';
  return b.stats.map((s) => String(s.n).replace(/^-(?=\d)/, '−').replace(/(\d)-(\d)/g, '$1–$2') + ' ' + s.l).join(' · ');
}
const rows = [['Title', 'Slug', 'Client', 'Categories', 'Industries', 'Summary', 'Thumbnail (file)', 'Lead video (Vimeo URL)', 'Write-up', 'Images to place (files)', 'Write-up coming soon', 'Featured',
  'Key results (one line)', 'Home panel: kicker', 'Home panel: big number', 'Home panel: after number', 'Home panel: outcome', 'Home panel: colour', 'Home panel: text colour', 'Home panel: image (file)', 'Home panel: image focus']];
S.projects.forEach((p) => {
  const m = S.featuredMeta[p.slug];
  rows.push([p.title, p.slug, p.client, p.categories.map(catName).join(', '), p.industries.map(indName).join(', '), p.summary,
    'framer/assets/thumbs/' + p.slug + '.webp', p.lead.t === 'vimeo' ? 'https://vimeo.com/' + p.lead.id : '', writeupHTML(p), imageList(p), p.placeholder ? 'true' : 'false', S.featured.indexOf(p.slug) > -1 ? 'true' : 'false',
    keyResults(p), m ? m.need : '', m ? m.metric : '', m ? m.words : '', m ? m.outcome : '', m ? m.color[0] : '', m ? m.color[1] : '', m ? 'framer/assets/featured/' + p.slug + '.webp' : '', m ? (m.pos || '50% 50%') : '']);
});
fs.writeFileSync(path.join(outCms, 'projects.csv'), csv(rows));

